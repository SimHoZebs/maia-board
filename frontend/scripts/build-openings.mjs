#!/usr/bin/env node
// Build the checked-in opening book from the pinned lichess-org/chess-openings
// source. Upstream TSVs carry (eco, name, pgn); UCI move lists and EPD position
// keys are derived here with the same chess.js semantics the runtime uses, so a
// row that does not replay to a single legal line fails the build instead of
// shipping a corrupt entry.
//
// Usage (from frontend/):
//   node scripts/build-openings.mjs           # regenerate src/openings.generated.ts
//   node scripts/build-openings.mjs --check   # CI: exit 1 when the artifact is stale
//
// Network: downloads a.tsv-e.tsv at PINNED_SHA (~3800 rows total).

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { Chess } from 'chess.js';

const PINNED_SHA = '4b8622759e7ae6f93f011cc6c83a3823401ab45e';
const PINNED_DATE = '2026-08-04';
const VOLUMES = ['a', 'b', 'c', 'd', 'e'];
const OUT_PATH = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'openings.generated.ts');

// EPD key: FEN without move counters, en-passant square only when a capture is
// actually legal. chess.js already blanks stale squares; the flags check covers
// the remaining pin-illegal case. Must stay identical to epdKey() in
// src/openings.ts.
function epdKey(fen) {
  const normalized = new Chess(fen).fen().split(' ');
  let ep = normalized[3];
  if (ep !== '-') {
    const probe = new Chess(fen);
    const hasEp = probe.moves({ verbose: true }).some((m) => m.flags.includes('e'));
    if (!hasEp) ep = '-';
  }
  return `${normalized[0]} ${normalized[1]} ${normalized[2]} ${ep}`;
}

async function fetchTsv(volume) {
  const url = `https://raw.githubusercontent.com/lichess-org/chess-openings/${PINNED_SHA}/${volume}.tsv`;
  const response = await fetch(url, { headers: { 'User-Agent': 'maia-board-build' } });
  if (!response.ok) throw new Error(`fetch ${url} failed (${response.status})`);
  return response.text();
}

async function build() {
  // EPD -> { eco, name, ply }. Duplicate EPDs (transposed paths to one board)
  // keep the most specific name; ties keep the deeper line.
  const table = new Map();
  let rows = 0;
  let collisions = 0;
  const failures = [];
  for (const volume of VOLUMES) {
    const text = await fetchTsv(volume);
    const lines = text.split('\n');
    for (let index = 1; index < lines.length; index++) {
      const line = lines[index].trimEnd();
      if (!line) continue;
      const fields = line.split('\t');
      if (fields.length !== 3) {
        failures.push(`${volume}.tsv:${index + 1}: expected 3 tab fields, got ${fields.length}`);
        continue;
      }
      const [eco, name, pgn] = fields;
      rows++;
      let game;
      try {
        game = new Chess();
        game.loadPgn(pgn);
      } catch (error) {
        failures.push(`${volume}.tsv:${index + 1} (${eco} ${name}): PGN replay failed: ${error.message}`);
        continue;
      }
      const history = game.history({ verbose: true });
      const ply = history.length;
      if (!ply) {
        failures.push(`${volume}.tsv:${index + 1} (${eco} ${name}): empty line`);
        continue;
      }
      const key = epdKey(game.fen());
      const prev = table.get(key);
      if (prev) {
        collisions++;
        if (name.length > prev.name.length || (name.length === prev.name.length && ply > prev.ply)) {
          table.set(key, { eco, name, ply });
        }
      } else {
        table.set(key, { eco, name, ply });
      }
    }
  }
  return { table, rows, collisions, failures };
}

function render(table, rows, collisions) {
  const keys = [...table.keys()].sort();
  const entries = keys.map((key) => {
    const { eco, name } = table.get(key);
    return `  ${JSON.stringify(key)}: ${JSON.stringify([eco, name])},`;
  });
  return `// Generated by scripts/build-openings.mjs — DO NOT EDIT.\n` +
    `// Source: lichess-org/chess-openings @ ${PINNED_SHA} (${PINNED_DATE}),\n` +
    `// a.tsv-e.tsv (${rows} rows, ${collisions} transposed-position collisions,\n` +
    `// most-specific name kept). CC0 public-domain dedication, see\n` +
    `// https://github.com/lichess-org/chess-openings.\n` +
    `// Regenerate: node scripts/build-openings.mjs (from frontend/).\n` +
    `export const OPENINGS_SHA = ${JSON.stringify(PINNED_SHA)};\n` +
    `export const OPENINGS: Record<string, readonly [eco: string, name: string]> = {\n` +
    entries.join('\n') +
    `\n};\n`;
}

const check = process.argv.includes('--check');
const { table, rows, collisions, failures } = await build();
if (failures.length) {
  console.error(`build-openings: ${failures.length} unparseable rows (showing 20):`);
  for (const failure of failures.slice(0, 20)) console.error(`  ${failure}`);
  process.exit(1);
}
if (table.size < 3000) {
  console.error(`build-openings: only ${table.size} positions from ${rows} rows — upstream truncation?`);
  process.exit(1);
}
const output = render(table, rows, collisions);
if (check) {
  const current = readFileSync(OUT_PATH, 'utf8');
  if (current !== output) {
    console.error('build-openings: src/openings.generated.ts is stale — run node scripts/build-openings.mjs');
    process.exit(1);
  }
  console.log(`build-openings: fresh (${table.size} positions, ${rows} rows, ${collisions} collisions)`);
} else {
  writeFileSync(OUT_PATH, output);
  console.log(`build-openings: wrote ${OUT_PATH} (${table.size} positions, ${rows} rows, ${collisions} collisions)`);
}
